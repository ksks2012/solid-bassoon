#!/usr/bin/env python3
"""Golden-regression harness for the GPU render (ticket 0011).

Expected behaviour from spec 0002 / ticket 0011:

- **Regression** — render each scene and compare against its committed
  reference on the raw float32 buffer. Tolerances are justified in
  `reference.DEFAULT_TOLERANCE`; the `jetoff` scene uses 0.0 because byte
  identity with the pre-jet baseline is the contract, not a tolerance.
- **Disk on/off locality** — re-render `jetoff` (disk on) and `diskoff`
  (disk off) *fresh*, then assert their delta is non-empty, does not touch the
  frame border, and lies inside the footprint committed by the references.
  Re-rendering means a code change that breaks locality fails here rather than
  hiding behind two references generated by the same bad code.
- **Exit codes** — 0 ok, 1 failure, 2 skipped (CTest SKIP_RETURN_CODE 2).
  A failure is never masked by a later skip.
- Shape is validated from the `<file>.meta` sidecar before any comparison.
"""
import argparse
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import compare
import reference


def regression_scene(renderer, reference_dir, scene, tol, threshold):
    ref_f32 = reference.scene_path(reference_dir, scene, ".f32")
    config = reference.scene_config(reference_dir, scene)
    staging = ref_f32 + ".regression"
    code, log = reference.render(renderer, config, staging)
    if code == 2:
        return {"scene": scene, "code": 2, "msg": log.strip()}
    if code != 0:
        return {"scene": scene, "code": 1,
                "msg": "renderer exited {}: {}".format(code, log.strip())}

    # Goldens are tied to the GL driver that produced them: llvmpipe is
    # numerically different from the GPU (spec 0002 "Further Notes"). A
    # mismatch is an honest skip, never a confusing numeric failure and never
    # a green pass.
    running = reference.gl_renderer_from_log(log)
    try:
        recorded = compare.read_meta(ref_f32 + ".meta").get("gl_renderer")
    except (OSError, ValueError, AttributeError):
        recorded = None
    if running and recorded and recorded not in ("unknown",) and running != recorded:
        return {"scene": scene, "code": 2,
                "msg": "GL driver mismatch: reference was generated on '{}', "
                       "running on '{}' — regenerate references on this driver "
                       "(update_reference.py --reason ...) instead".format(recorded, running)}
    if not os.path.exists(staging + ".meta"):
        return {"scene": scene, "code": 1, "msg": "missing sidecar"}
    try:
        report = compare.compare_files(ref_f32, staging, threshold=threshold)
    except (OSError, ValueError) as exc:
        return {"scene": scene, "code": 1, "msg": str(exc)}
    finally:
        for path in (staging, staging + ".meta"):
            if os.path.exists(path):
                os.remove(path)
    if report["max_abs"] <= tol:
        return {"scene": scene, "code": 0, "report": report}
    return {"scene": scene, "code": 1, "report": report, "msg": "max_abs > tol"}


def disk_delta_locality(renderer, reference_dir, threshold, margin=4):
    """Ticket 0011 invariant: the disk on/off delta is confined to the disk.

    Renders both scenes fresh (so the check exercises *current* code) and
    asserts:
      1. the toggle actually changes something (non-empty delta),
      2. no differing pixel touches the frame border,
      3. the fresh delta bbox lies inside the footprint committed by the two
         references (`bbox_within`, expanded by `margin` px).
    """
    on_f32 = reference.scene_path(reference_dir, "jetoff", ".f32")
    off_f32 = reference.scene_path(reference_dir, "diskoff", ".f32")
    if not (os.path.exists(on_f32) and os.path.exists(off_f32)):
        return {"code": 2, "msg": "disk delta needs jetoff and diskoff references"}

    # Footprint committed by the references (stand-in for "the disk region").
    try:
        on_ref = compare.load_f32(on_f32)
        off_ref = compare.load_f32(off_f32)
        meta = compare.read_meta(on_f32 + ".meta")
        width, height, _ = compare.shape_from_meta(meta, len(on_ref), on_f32)
    except (OSError, ValueError) as exc:
        return {"code": 1, "msg": "cannot read references: {}".format(exc)}
    committed = reference.pixel_diff(on_ref, off_ref, width, height, threshold)
    if committed["bbox"] is None:
        return {"code": 1, "msg": "committed disk delta empty — toggle inert in references"}
    footprint = committed["bbox"]

    # Fresh renders under current code.
    staging = {"jetoff": off_f32 + ".delta_on", "diskoff": off_f32 + ".delta_off"}
    fresh = {}
    running = None
    for scene, path in staging.items():
        code, log = reference.render(renderer, reference.scene_config(reference_dir, scene), path)
        if running is None:
            running = reference.gl_renderer_from_log(log)
            try:
                recorded = compare.read_meta(on_f32 + ".meta").get("gl_renderer")
            except (OSError, ValueError, AttributeError):
                recorded = None
            if (running and recorded and recorded != "unknown"
                    and running != recorded):
                return {"code": 2,
                        "msg": "GL driver mismatch (footprint came from '{}', "
                               "running on '{}')".format(recorded, running)}
        if code == 2:
            return {"code": 2, "msg": "renderer skipped: {}".format(log.strip())}
        if code != 0 or not os.path.exists(path):
            return {"code": 1,
                    "msg": "renderer failed for {}: {}".format(scene, log.strip())}
        fresh[scene] = compare.load_f32(path)
        os.remove(path)
        if os.path.exists(path + ".meta"):
            os.remove(path + ".meta")

    delta = reference.pixel_diff(fresh["jetoff"], fresh["diskoff"], width, height, threshold)
    count, bbox = delta["count"], delta["bbox"]
    if count == 0:
        return {"code": 1, "msg": "fresh disk delta empty: disk.enabled has no effect"}

    x0, y0, x1, y1 = bbox
    if x0 == 0 or y0 == 0 or x1 == width - 1 or y1 == height - 1:
        return {"code": 1, "msg": "disk delta touches the frame border {}".format(bbox)}
    if not reference.bbox_within(bbox, footprint, margin):
        return {"code": 1,
                "msg": "fresh disk delta {} escapes committed footprint {} (margin {})".format(
                    bbox, footprint, margin)}

    bbox_area = (x1 - x0 + 1) * (y1 - y0 + 1)
    frame_area = width * height
    return {"code": 0,
            "msg": "{} px differ, bbox={} inside footprint {} ({}/{} frame area)".format(
                count, bbox, footprint, bbox_area, frame_area)}


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--renderer", default=reference.DEFAULT_RENDERER)
    parser.add_argument("--reference-dir", default=reference.DEFAULT_REFERENCE_DIR)
    parser.add_argument("--tolerance", type=float, default=reference.DEFAULT_TOLERANCE)
    parser.add_argument("--threshold", type=float, default=reference.DEFAULT_THRESHOLD)
    args = parser.parse_args(argv)

    if not os.path.exists(args.renderer):
        print("SKIP: renderer not found: {}".format(args.renderer), file=sys.stderr)
        return 2

    scenes = reference.scene_names(args.reference_dir)
    failed = False
    skipped = False
    for scene in scenes:
        # jetoff: byte identity with the pre-jet baseline is the contract.
        tol = 0.0 if scene == "jetoff" else args.tolerance
        res = regression_scene(args.renderer, args.reference_dir, scene, tol, args.threshold)
        if res["code"] == 2:
            print("SKIP {}: {}".format(res["scene"], res.get("msg", "")))
            skipped = True
            continue
        if res["code"] != 0:
            failed = True
            print("FAIL {}: {}".format(res["scene"], res.get("msg", "")), file=sys.stderr)
            if res.get("report"):
                print("      {}".format(compare.format_report(res["report"])),
                      file=sys.stderr)
            continue
        print("PASS {}: {}".format(res["scene"], compare.format_report(res["report"])))

    # ── Disk on/off locality invariant ────────────────────────────────────────
    # Always run: filtering scenes out must not silently drop the invariant.
    delta = disk_delta_locality(args.renderer, args.reference_dir, args.threshold)
    if delta["code"] == 2:
        print("SKIP disk-delta: {}".format(delta["msg"]))
        skipped = True
    elif delta["code"] != 0:
        failed = True
        print("FAIL disk-delta: {}".format(delta["msg"]), file=sys.stderr)
    else:
        print("PASS disk-delta: {}".format(delta["msg"]))

    # A failure always wins over a later skip — a skip must never mask it.
    if failed:
        return 1
    if skipped:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
